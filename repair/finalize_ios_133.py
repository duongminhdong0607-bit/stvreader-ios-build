#!/usr/bin/env python3
"""Finalize iOS display metadata and icon from the user's STV 1.3.3 APK resources."""
from pathlib import Path
import json
import plistlib
import subprocess
import sys

root=Path("ios/App/App")
info=root/"Info.plist"
if not info.is_file():
    raise SystemExit("Missing Info.plist generated by Capacitor iOS")
with info.open("rb") as fp:
    values=plistlib.load(fp)
values.update({
    "CFBundleDisplayName": "STV MobileReader",
    "CFBundleShortVersionString": "1.3.3",
    "CFBundleVersion": "13303",
    "NSCameraUsageDescription": "Sử dụng camera khi bạn yêu cầu chụp ảnh trong ứng dụng.",
    "NSPhotoLibraryUsageDescription": "Truy cập ảnh khi bạn chủ động chọn ảnh trong ứng dụng.",
    "NSPhotoLibraryAddUsageDescription": "Lưu ảnh khi bạn yêu cầu xuất ảnh từ ứng dụng."
})
with info.open("wb") as fp:
    plistlib.dump(values,fp)
icon_source=Path("www/assets/imgs/logo.png")
if not icon_source.is_file():
    raise SystemExit("Cannot find STV 1.3.3 logo")
icon_folder=root/"Assets.xcassets"/"AppIcon.appiconset"
icon_folder.mkdir(parents=True,exist_ok=True)
content_file=icon_folder/"Contents.json"
if content_file.is_file():
    data=json.loads(content_file.read_text())
else:
    data={"images":[{"filename":"AppIcon-512@2x.png","idiom":"universal","platform":"ios","size":"1024x1024"}],"info":{"author":"xcode","version":1}}
names={x.get("filename") for x in data.get("images",[]) if x.get("filename")}
if not names:
    data={"images":[{"filename":"AppIcon-512@2x.png","idiom":"universal","platform":"ios","size":"1024x1024"}],"info":{"author":"xcode","version":1}}
    names={"AppIcon-512@2x.png"}
content_file.write_text(json.dumps(data,ensure_ascii=False,indent=2))
for icon_name in names:
    subprocess.run(["sips","-s","format","png","-z","1024","1024",str(icon_source),"--out",str(icon_folder/icon_name)],check=True,stdout=subprocess.DEVNULL)
print("STV iOS 1.3.3 metadata and logo updated; icons",sorted(names))
